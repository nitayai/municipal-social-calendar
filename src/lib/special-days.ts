/**
 * Get the special day name for a given "YYYY-MM-DD" string.
 * Checks year-specific days first (they override generic MM-DD),
 * then falls back to the fixed MM-DD map.
 * Returns null if none.
 */
export function getSpecialDay(dateStr: string): string | null {
  if (YEAR_SPECIFIC_DAYS[dateStr]) return YEAR_SPECIFIC_DAYS[dateStr];
  const mmdd = dateStr.slice(5);
  return SPECIAL_DAYS[mmdd] ?? null;
}

/**
 * Batch lookup \u2013 returns a Map keyed by "YYYY-MM-DD".
 */
export function getSpecialDaysForDates(
  dateStrings: string[]
): Map<string, string> {
  const map = new Map<string, string>();
  for (const ds of dateStrings) {
    const name = getSpecialDay(ds);
    if (name) map.set(ds, name);
  }
  return map;
}
